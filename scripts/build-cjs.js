// Generates the CommonJS entry (index.cjs) and its types (index.d.cts) from the ESM sources.
// Usage: node scripts/build-cjs.js          write the files
//        node scripts/build-cjs.js --check  exit 1 if they are out of date
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = (file) => fileURLToPath(new URL(`../${file}`, import.meta.url));
const banner = "// Generated by scripts/build-cjs.js from index.js. Do not edit.\n";

function replaceOnce(text, from, to, file) {
  if (text.split(from).length !== 2) throw new Error(`expected exactly one "${from}" in ${file}`);
  return text.replace(from, to);
}

const esm = readFileSync(root("index.js"), "utf8");
const cjs =
  banner +
  replaceOnce(
    esm,
    "export default Queue;\nexport { Queue, AsyncQueue, PriorityQueue, QueueClosedError };",
    "module.exports = { Queue, AsyncQueue, PriorityQueue, QueueClosedError };",
    "index.js",
  );

// CommonJS consumers use the named exports: const { Queue } = require("queue-list")
const types = readFileSync(root("index.d.ts"), "utf8");
const cts = banner + replaceOnce(types, "export default Queue;\n", "", "index.d.ts");

const outputs = { "index.cjs": cjs, "index.d.cts": cts };

if (process.argv.includes("--check")) {
  const stale = Object.entries(outputs).filter(([file, text]) => {
    try { return readFileSync(root(file), "utf8") !== text; } catch { return true; }
  });
  if (stale.length) {
    console.error(`out of date: ${stale.map(([file]) => file).join(", ")} (run npm run build)`);
    process.exit(1);
  }
} else {
  for (const [file, text] of Object.entries(outputs)) writeFileSync(root(file), text);
}
